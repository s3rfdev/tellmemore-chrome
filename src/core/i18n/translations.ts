/**
 * @file src/core/i18n/translations.ts
 * @description Internationalization dictionary supporting 6 languages (EN, RU, ES, DE, FR, PL)
 * with automatic system language detection via chrome.i18n and navigator.language.
 */

export type LanguageCode = 'en' | 'ru' | 'pl' | 'es' | 'de' | 'fr';

export const SUPPORTED_LANGUAGES: Array<{ code: LanguageCode; name: string; nativeName: string }> = [
  { code: 'ru', name: 'Russian', nativeName: 'Русский' },
  { code: 'en', name: 'English', nativeName: 'English' },
  { code: 'pl', name: 'Polish', nativeName: 'Polski' },
  { code: 'es', name: 'Spanish', nativeName: 'Español' },
  { code: 'de', name: 'German', nativeName: 'Deutsch' },
  { code: 'fr', name: 'French', nativeName: 'Français' },
];

/**
 * Automatically detects the user's OS / browser system language.
 */
export function detectSystemLanguage(): LanguageCode {
  try {
    const raw = (
      (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage?.()) ||
      (typeof navigator !== 'undefined' && navigator.language) ||
      'en'
    ).toLowerCase();

    if (raw.startsWith('ru') || raw.startsWith('uk') || raw.startsWith('be')) return 'ru';
    if (raw.startsWith('pl')) return 'pl';
    if (raw.startsWith('es')) return 'es';
    if (raw.startsWith('de')) return 'de';
    if (raw.startsWith('fr')) return 'fr';
    return 'en';
  } catch {
    return 'en';
  }
}

